import { holes, partSize, solids } from './geometry';
import { labelWithName, mm, type Model, type Part } from './types';

function solidCode(p: Part): string {
  const c = `// ${labelWithName(p)}: ${partSize(p)}`;
  switch (p.shape) {
    case 'box':
      return `${c}\ntranslate([${mm(p.x - p.sx / 2)}, ${mm(p.y - p.sy / 2)}, ${mm(p.z)}]) cube([${mm(p.sx)}, ${mm(p.sy)}, ${mm(p.sz)}]);`;
    case 'cylinder':
      return `${c}\ntranslate([${mm(p.x)}, ${mm(p.y)}, ${mm(p.z)}]) cylinder(h = ${mm(p.sz)}, d = ${mm(p.sx)}, $fn = 64);`;
    case 'sphere':
      return `${c}\ntranslate([${mm(p.x)}, ${mm(p.y)}, ${mm(p.z + p.sz / 2)}]) sphere(d = ${mm(p.sx)}, $fn = 64);`;
    case 'cone':
      return `${c}\ntranslate([${mm(p.x)}, ${mm(p.y)}, ${mm(p.z)}]) cylinder(h = ${mm(p.sz)}, d1 = ${mm(p.sx)}, d2 = ${mm(p.topD ?? 0)}, $fn = 64);`;
    default:
      return '';
  }
}

function holeCode(h: Part): string {
  return `// ${labelWithName(h)}: ${partSize(h)}\ntranslate([${mm(h.x)}, ${mm(h.y)}, ${mm(h.z)}]) cylinder(h = ${mm(h.sz)}, d = ${mm(h.sx)}, $fn = 48);`;
}

const indent = (s: string, n: number) => s.split('\n').map((l) => ' '.repeat(n) + l).join('\n');

export function toScad(m: Model): string {
  const header = [
    '// Generated by the 3D Design Agent demo.',
    '// Units: millimetres. X = left to right, Y = front to back, Z = up. The build plate is z = 0.',
    '',
  ].join('\n');
  const S = solids(m), H = holes(m);
  if (!S.length) return `${header}// The model is empty.\n`;
  const body = S.map(solidCode).join('\n\n');
  if (!H.length) return `${header}union() {\n${indent(body, 2)}\n}\n`;
  return `${header}difference() {\n  union() {\n${indent(body, 4)}\n  }\n\n${indent(H.map(holeCode).join('\n\n'), 2)}\n}\n`;
}
