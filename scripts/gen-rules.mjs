// Generates firestore.rules from src/checklist.json and the admin allowlist.
// Run: npm run rules   (also runs automatically before build/deploy)
//
// Model (schemaVersion 3):
//   sessions/{code}                   created by the operator; read with the code by the participant;
//                                     the participant may only write their own progress + answers.
//   sessions/{code}/private/operator  operator notes, recording marks, transcript, measurements (admin only).
import { readFileSync, writeFileSync } from 'node:fs';
import { adminEmails } from './admin-emails.mjs';

const checklist = JSON.parse(readFileSync('src/checklist.json', 'utf8'));
const itemIds = checklist.flatMap((c) => c.items.map((i) => i.id));
const MAX_ISSUES = 30; // keep in sync with LIMITS.maxIssues in src/types.ts
const emails = adminEmails();
if (emails.length === 0) console.warn('WARNING: no admin emails found; nobody will be able to read data.');

const q = (s) => JSON.stringify(s);
// Firestore rules cap a request at 1000 evaluated expressions and each nested field check costs
// ~15, so answers are stored as flat maps/lists and validated with keys()/values().hasOnly()/join().
const ids = q(itemIds);
const N = itemIds.length;
const TAG_LIST = q(['Verifying spatial output', 'Describing spatial relations', 'Tracking edits', 'Other']);
const GROUPS = q(['Sighted pilot (blindfolded)', 'BLV screen-reader user']);
const CONDITIONS = q(['A: OpenSCAD + ChatGPT', 'B: OpenSCAD + Claude']);
const OPERATOR_FIELDS = ['schemaVersion', 'auditor', 'group', 'condition', 'screenReader', 'task', 'status', 'createdAt', 'createdBy'];
const PARTICIPANT_FIELDS = ['participantUid', 'status', 'joinedAt', 'taskStartedAt', 'taskEndedAt', 'submittedAt',
  'answers', 'comments', 'issueTexts', 'issueTags', 'issueSeverities', 'verificationAnswer', 'verificationReason'];
const RESPONSE_FIELDS = ['answers', 'comments', 'issueTexts', 'issueTags', 'issueSeverities', 'verificationAnswer', 'verificationReason'];

const rules = `rules_version = '2';
// GENERATED by scripts/gen-rules.mjs from src/checklist.json and the admin email list. Do not edit by hand.
service cloud.firestore {
  match /databases/{database}/documents {

    function isAdmin() {
      return request.auth != null
        && request.auth.token.email_verified == true
        && request.auth.token.email.lower() in ${q(emails)};
    }

    function str(v, min, max) {
      return v is string && v.size() >= min && v.size() <= max;
    }

    // ---- operator creates a session ----
    function validNewSession(d) {
      return d.keys().hasOnly(${q(OPERATOR_FIELDS)})
        && d.keys().hasAll(${q(OPERATOR_FIELDS)})
        && d.schemaVersion == 3
        && d.status == 'created'
        && d.createdAt == request.time
        && d.createdBy == request.auth.token.email
        && str(d.auditor, 1, 40)
        && d.group in ${GROUPS}
        && d.condition in ${CONDITIONS}
        && str(d.screenReader, 0, 100)
        && str(d.task, 0, 4000);
    }

    // ---- participant answers (checked when they submit) ----
    function validResponses(d) {
      return d.keys().hasAll(${q(RESPONSE_FIELDS)})
        && d.answers is map && d.answers.size() == ${N}
        && d.answers.keys().hasOnly(${ids})
        && d.answers.values().hasOnly([0, 1, 2, 3, 4, 'NA'])
        && d.comments is map && d.comments.size() == ${N}
        && d.comments.keys().hasOnly(${ids})
        && d.comments.values().join('').size() <= ${N * 1000}
        && d.issueTexts is list && d.issueTags is list && d.issueSeverities is list
        && d.issueTexts.size() <= ${MAX_ISSUES}
        && d.issueTags.size() == d.issueTexts.size()
        && d.issueSeverities.size() == d.issueTexts.size()
        && !('' in d.issueTexts)
        && d.issueTexts.join('').size() <= ${MAX_ISSUES * 2000}
        && d.issueTags.hasOnly(${TAG_LIST})
        && d.issueSeverities.hasOnly([0, 1, 2, 3, 4])
        && d.verificationAnswer in ['Correct', 'Incorrect', 'Could not tell']
        && str(d.verificationReason, 0, 2000);
    }

    // A timestamp field may only be set once, to the server time.
    function stampOnce(changed, o, d, k) {
      return !changed.hasAny([k]) || (o.get(k, null) == null && d[k] == request.time);
    }

    // ---- participant progress: join, start task, finish task, submit ----
    function participantUpdate() {
      let o = resource.data;
      let d = request.resource.data;
      let changed = d.diff(o).affectedKeys();
      return request.auth != null
        && o.get('schemaVersion', 0) == 3
        && changed.hasOnly(${q(PARTICIPANT_FIELDS)})
        && o.status != 'submitted'
        && o.get('participantUid', null) in [null, request.auth.uid]
        && d.participantUid == request.auth.uid
        && d.status in ['joined', 'in_task', 'task_done', 'submitted']
        && stampOnce(changed, o, d, 'joinedAt')
        && stampOnce(changed, o, d, 'taskStartedAt')
        && stampOnce(changed, o, d, 'taskEndedAt')
        && stampOnce(changed, o, d, 'submittedAt')
        && (d.status != 'in_task' || d.get('taskStartedAt', null) != null)
        && (d.status != 'task_done' || d.get('taskEndedAt', null) != null)
        && (d.status != 'submitted' || (d.get('submittedAt', null) != null && d.get('taskEndedAt', null) != null && validResponses(d)))
        && (d.status == 'submitted' || !changed.hasAny(${q(RESPONSE_FIELDS)}));
    }

    match /sessions/{code} {
      allow get: if request.auth != null;            // participant needs the code to read
      allow list: if isAdmin();
      allow create: if isAdmin() && validNewSession(request.resource.data);
      allow update: if isAdmin() || participantUpdate();
      allow delete: if isAdmin();

      match /private/{doc} {
        allow read, write: if isAdmin();
      }
    }

    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
writeFileSync('firestore.rules', rules);
console.log(`firestore.rules written (${itemIds.length} items, admins: ${emails.join(', ') || 'NONE'})`);
