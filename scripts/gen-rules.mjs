// Generates firestore.rules from src/checklist.json and the admin allowlist.
// Run: npm run rules   (also runs automatically before build/deploy)
import { readFileSync, writeFileSync } from 'node:fs';
import { adminEmails } from './admin-emails.mjs';

const checklist = JSON.parse(readFileSync('src/checklist.json', 'utf8'));
const itemIds = checklist.flatMap((c) => c.items.map((i) => i.id));
const MAX_ISSUES = 30; // keep in sync with LIMITS.maxIssues in src/types.ts
const emails = adminEmails();
if (emails.length === 0) console.warn('WARNING: no admin emails found; nobody will be able to read data.');

const q = (s) => JSON.stringify(s);
// Why the data is shaped as flat maps/lists: Firestore rules cap a request at 1000 evaluated
// expressions, and each nested field check costs ~15. So the rules validate whole collections at
// once (keys().hasOnly, values().hasOnly, join) instead of looping over items. Per-field length
// limits are enforced in the app; the rules enforce totals.
const ids = q(itemIds);
const N = itemIds.length;
const TAG_LIST = q(['Verifying spatial output', 'Describing spatial relations', 'Tracking edits', 'Other']);
const FIELDS = q(['schemaVersion', 'uid', 'auditor', 'group', 'condition', 'screenReader', 'answers', 'comments',
  'issueTexts', 'issueTags', 'issueSeverities', 'verificationAnswer', 'verificationReason', 'submittedAt']);

const rules = `rules_version = '2';
// GENERATED by scripts/gen-rules.mjs from src/checklist.json and the admin email list. Do not edit by hand.
service cloud.firestore {
  match /databases/{database}/documents {

    function isAdmin() {
      return request.auth != null
        && request.auth.token.email_verified == true
        && request.auth.token.email.lower() in ${q(emails)};
    }

    function str(v, min, max) {
      return v is string && v.size() >= min && v.size() <= max;
    }

    function validSession(d) {
      return d.keys().hasOnly(${FIELDS})
        && d.keys().hasAll(${FIELDS})
        && d.schemaVersion == 2
        && d.uid == request.auth.uid
        && d.submittedAt == request.time
        && str(d.auditor, 1, 40)
        && d.group in ['Sighted pilot (blindfolded)', 'BLV screen-reader user']
        && d.condition in ['A: OpenSCAD + ChatGPT', 'B: OpenSCAD + Claude']
        && str(d.screenReader, 1, 100)
        // every checklist item answered with 0-4 or "NA" (Unclear / N/A)
        && d.answers is map && d.answers.size() == ${N}
        && d.answers.keys().hasOnly(${ids})
        && d.answers.values().hasOnly([0, 1, 2, 3, 4, 'NA'])
        // one comment string per item (join() fails on non-strings); total size cap
        && d.comments is map && d.comments.size() == ${N}
        && d.comments.keys().hasOnly(${ids})
        && d.comments.values().join('').size() <= ${N * 1000}
        // outside-framework issues as parallel lists
        && d.issueTexts is list && d.issueTags is list && d.issueSeverities is list
        && d.issueTexts.size() <= ${MAX_ISSUES}
        && d.issueTags.size() == d.issueTexts.size()
        && d.issueSeverities.size() == d.issueTexts.size()
        && !('' in d.issueTexts)
        && d.issueTexts.join('').size() <= ${MAX_ISSUES * 2000}
        && d.issueTags.hasOnly(${TAG_LIST})
        && d.issueSeverities.hasOnly([0, 1, 2, 3, 4])
        && d.verificationAnswer in ['Correct', 'Incorrect', 'Could not tell']
        && str(d.verificationReason, 0, 2000);
    }

    match /sessions/{sessionId} {
      allow create: if request.auth != null && validSession(request.resource.data);
      allow read: if isAdmin();   // covers get and list
      allow update, delete: if false;
    }

    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
writeFileSync('firestore.rules', rules);
console.log(`firestore.rules written (${itemIds.length} items, admins: ${emails.join(', ') || 'NONE'})`);
