// Generates firestore.rules from src/checklist.json and the admin allowlist.
// Run: npm run rules   (also runs automatically before build/deploy)
import { readFileSync, writeFileSync } from 'node:fs';
import { adminEmails } from './admin-emails.mjs';

const checklist = JSON.parse(readFileSync('src/checklist.json', 'utf8'));
const itemIds = checklist.flatMap((c) => c.items.map((i) => i.id));
const MAX_ISSUES = 30; // keep in sync with LIMITS.maxIssues in src/types.ts
const emails = adminEmails();
if (emails.length === 0) console.warn('WARNING: no admin emails found; nobody will be able to read data.');

const q = (s) => JSON.stringify(s);
const issueChecks = Array.from({ length: MAX_ISSUES }, (_, i) => `(o.size() <= ${i} || validIssue(o[${i}]))`).join('\n        && ');

const rules = `rules_version = '2';
// GENERATED by scripts/gen-rules.mjs. Do not edit by hand.
service cloud.firestore {
  match /databases/{database}/documents {

    function isAdmin() {
      return request.auth != null
        && request.auth.token.email_verified == true
        && request.auth.token.email.lower() in ${q(emails)};
    }

    function str(v, min, max) {
      return v is string && v.size() >= min && v.size() <= max;
    }

    function validSeverity(v) {
      return v is int && v >= 0 && v <= 4;
    }

    function validItem(v) {
      return v is map
        && v.keys().hasOnly(['severity', 'unclear', 'comment'])
        && v.keys().hasAll(['severity', 'unclear', 'comment'])
        && v.unclear is bool
        && ((v.unclear == true && v.severity == null) || (v.unclear == false && validSeverity(v.severity)))
        && str(v.comment, 0, 1000);
    }

    function validItems(m) {
      return m is map
        && m.keys().hasOnly(${q(itemIds)})
        && m.keys().hasAll(${q(itemIds)})
        && ${itemIds.map((id) => `validItem(m[${q(id)}])`).join('\n        && ')};
    }

    function validIssue(v) {
      return v is map
        && v.keys().hasOnly(['text', 'tag', 'severity'])
        && v.keys().hasAll(['text', 'tag', 'severity'])
        && str(v.text, 1, 2000)
        && v.tag in ['Verifying spatial output', 'Describing spatial relations', 'Tracking edits', 'Other']
        && validSeverity(v.severity);
    }

    function validIssues(o) {
      return o is list && o.size() <= ${MAX_ISSUES}
        && ${issueChecks};
    }

    function validSession(d) {
      return d.keys().hasOnly(['schemaVersion', 'uid', 'auditor', 'group', 'condition', 'screenReader', 'items', 'outside', 'verification', 'submittedAt'])
        && d.keys().hasAll(['schemaVersion', 'uid', 'auditor', 'group', 'condition', 'screenReader', 'items', 'outside', 'verification', 'submittedAt'])
        && d.schemaVersion == 1
        && d.uid == request.auth.uid
        && str(d.auditor, 1, 40)
        && d.group in ['Sighted pilot (blindfolded)', 'BLV screen-reader user']
        && d.condition in ['A: OpenSCAD + ChatGPT', 'B: OpenSCAD + Claude']
        && str(d.screenReader, 1, 100)
        && d.submittedAt == request.time
        && d.verification is map
        && d.verification.keys().hasOnly(['answer', 'reason'])
        && d.verification.keys().hasAll(['answer', 'reason'])
        && d.verification.answer in ['Correct', 'Incorrect', 'Could not tell']
        && str(d.verification.reason, 0, 2000)
        && validItems(d.items)
        && validIssues(d.outside);
    }

    match /sessions/{sessionId} {
      allow create: if request.auth != null && validSession(request.resource.data);
      allow read: if isAdmin();   // covers get and list
      allow update, delete: if false;
    }

    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
writeFileSync('firestore.rules', rules);
console.log(`firestore.rules written (${itemIds.length} items, admins: ${emails.join(', ') || 'NONE'})`);
